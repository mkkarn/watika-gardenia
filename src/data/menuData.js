export const getFeaturedItems = () => menuItems.filter((item) => item.featured);
export const getItemsByCategory = (category) =>
  category === "all" ? menuItems : menuItems.filter((item) => item.category === category);
export const getItemById = (id) => menuItems.find((item) => item.id === id);
export const getRecommendations = (currentItemId, limit = 4) => {
  const current = getItemById(currentItemId);
  if (!current) return menuItems.slice(0, limit);
  return menuItems
    .filter((item) => item.id !== currentItemId && (item.category === current.category || item.rating >= 4.7))
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
};
